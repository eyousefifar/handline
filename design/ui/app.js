const ui = { lang: "en", link: "linked", audio: "a", bag: "home", hand: "texts" };

function readHash() {
  const parts = location.hash.replace(/^#/, "").split("/");
  if (parts.length < 5) return;
  const [lang, link, audio, bag, hand] = parts;
  if (copy[lang]) ui.lang = lang;
  if (link === "linked" || link === "away") ui.link = link;
  if (audio === "a" || audio === "b") ui.audio = audio;
  const bagOk = ["permissions", "qr", "home", "audio", "unpair"];
  const handOk = ["scan", "texts", "thread", "keypad", "recents", "people", "incoming", "active", "code"];
  if (bagOk.includes(bag)) ui.bag = bag;
  if (handOk.includes(hand)) ui.hand = hand;
}

function apply() {
  const pack = copy[ui.lang];
  document.body.dir = ui.lang === "fa" ? "rtl" : "ltr";
  document.body.lang = ui.lang === "fa" ? "fa" : "en";
  document.body.dataset.link = ui.link;
  document.body.dataset.audio = ui.audio;
  document.querySelectorAll("[data-k]").forEach((el) => {
    const value = pack[el.dataset.k];
    if (value == null) console.warn("missing", el.dataset.k);
    else el.textContent = value;
  });
  document.querySelectorAll("[data-k-placeholder]").forEach((el) => {
    el.placeholder = pack[el.dataset.kPlaceholder] || "";
  });
  document.querySelectorAll("[data-bag]").forEach((el) => {
    el.hidden = el.dataset.bag !== ui.bag;
  });
  document.querySelectorAll("[data-hand]").forEach((el) => {
    el.hidden = el.dataset.hand !== ui.hand;
  });
  document.querySelector("[data-phone=hand]").dataset.show = ui.hand;
  document.querySelectorAll("[data-go]").forEach((el) => {
    const on = el.dataset.go === "bag" ? el.dataset.screen === ui.bag : el.dataset.screen === ui.hand;
    if (el.closest(".index, .tabs")) el.setAttribute("aria-current", on ? "true" : "false");
  });
  document.querySelectorAll("[data-set]").forEach((el) => {
    el.setAttribute("aria-pressed", String(ui[el.dataset.set] === el.dataset.value));
  });
  const call = document.querySelector(".call");
  if (call) call.disabled = ui.link === "away";
  const next = `#${ui.lang}/${ui.link}/${ui.audio}/${ui.bag}/${ui.hand}`;
  if (location.hash !== next) history.replaceState(null, "", next);
}

readHash();

document.addEventListener("click", (event) => {
  const set = event.target.closest("[data-set]");
  if (set) {
    ui[set.dataset.set] = set.dataset.value;
    apply();
    return;
  }
  const go = event.target.closest("[data-go]");
  if (!go) return;
  ui[go.dataset.go] = go.dataset.screen;
  apply();
});

apply();
requestAnimationFrame(() => document.body.classList.add("ready"));
